import Foundation

/// Maps a local domain `<name>.localhost` to a container through an app-managed Caddy container (G23).
///
/// - No DNS changes: browsers and curl already resolve `*.localhost` to loopback.
/// - HTTPS uses Caddy's internal CA (`local_certs`). Trusting its root CA on macOS is a separate,
///   opt-in step (`LocalProxy.trustRootCertificate`).
/// - The proxy runs with `network_mode: host` in the VM and binds only 127.0.0.1; Colima forwards
///   those ports to the Mac's localhost.
struct ProxyRoute: Codable, Identifiable, Hashable, Sendable {
    var id = UUID()
    /// The part before `.localhost`, e.g. `api` or `api.shop`.
    var subdomain: String
    /// Target container by **name**, which stays stable when compose recreates the container.
    var container: String
    var port: Int

    var host: String { "\(subdomain).localhost" }

    static func isValidSubdomain(_ value: String) -> Bool {
        let labels = value.split(separator: ".", omittingEmptySubsequences: false)
        guard !labels.isEmpty, value.count <= 200 else { return false }
        return labels.allSatisfy { label in
            label.range(of: #"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$"#, options: .regularExpression) != nil
        }
    }

    static func isValidContainerName(_ value: String) -> Bool {
        value.range(of: #"^[a-zA-Z0-9][a-zA-Z0-9_.-]*$"#, options: .regularExpression) != nil
    }

    var isValid: Bool {
        Self.isValidSubdomain(subdomain) && Self.isValidContainerName(container) && (1...65_535).contains(port)
    }
}

struct ProxySettings: Codable, Equatable, Sendable {
    var httpPort = 80
    var httpsPort = 443
    var https = true

    var isValid: Bool {
        (1...65_535).contains(httpPort) && (1...65_535).contains(httpsPort) && httpPort != httpsPort
    }

    func url(for route: ProxyRoute) -> String {
        if https {
            return "https://\(route.host)" + (httpsPort == 443 ? "" : ":\(httpsPort)")
        }
        return "http://\(route.host)" + (httpPort == 80 ? "" : ":\(httpPort)")
    }
}

enum LocalProxy {
    static let containerName = "colimax-proxy"
    static let label = "dev.colimax.proxy"
    static let image = "caddy:2-alpine"
    static let dataVolume = "colimax-proxy-data"
    static let caddyfilePath = "/etc/caddy"
    static let rootCertPath = "/data/caddy/pki/authorities/local/root.crt"
    /// Admin API on a unix socket inside the container: the proxy uses host networking, so the default
    /// port 2019 could clash with another process in the VM (or the integration-test proxy).
    static let adminAddress = "unix//tmp/caddy-admin.sock"

    enum ProxyError: LocalizedError, Equatable {
        case targetMissing(String)
        case targetNoNetwork(String)
        case reloadFailed(String)
        case invalid(String)

        var errorDescription: String? {
            switch self {
            case .targetMissing(let name): String(localized: "Container \(name) not found.")
            case .targetNoNetwork(let name): String(localized: "Container \(name) is not attached to any network.")
            case .reloadFailed(let message): String(localized: "Caddy rejected the configuration: \(message)")
            case .invalid(let message): message
            }
        }
    }

    /// Upstream for a route: the container's IP on one of its networks (user networks preferred,
    /// default `bridge` last). With `network_mode: host` the proxy can reach every bridge network
    /// without joining the user's networks (joining would make `docker compose down` fail with
    /// "network has active endpoints"). The IP changes when the container restarts, so the app
    /// re-applies the configuration then.
    struct Upstream: Equatable, Sendable {
        let route: ProxyRoute
        let address: String
    }

    static func upstream(for route: ProxyRoute, target: ContainerDetails) throws -> Upstream {
        let networks = target.networkSettings?.networks ?? [:]
        let preferred = networks.keys.sorted { lhs, rhs in
            (lhs == "bridge" ? 1 : 0, lhs) < (rhs == "bridge" ? 1 : 0, rhs)
        }
        for name in preferred {
            if let ip = networks[name]?.ipAddress, !ip.isEmpty {
                return Upstream(route: route, address: "\(ip):\(route.port)")
            }
        }
        throw ProxyError.targetNoNetwork(route.container)
    }

    /// Caddyfile generated from validated routes only (no special characters reach the file).
    /// Binds only 127.0.0.1 in the VM; Colima forwards those ports to the Mac's localhost.
    static func caddyfile(_ upstreams: [Upstream], settings: ProxySettings) -> String {
        var lines = ["# Generated by ColimaX. Edits are overwritten.", "{",
                     "\tadmin \(adminAddress)",
                     "\tdefault_bind 127.0.0.1",
                     "\thttp_port \(settings.httpPort)",
                     "\thttps_port \(settings.httpsPort)"]
        lines.append(settings.https ? "\tlocal_certs" : "\tauto_https off")
        lines.append("}")
        for upstream in upstreams.sorted(by: { $0.route.host < $1.route.host }) where upstream.route.isValid {
            let site = settings.https ? upstream.route.host : "http://\(upstream.route.host)"
            lines += ["", "\(site) {", "\treverse_proxy \(upstream.address)", "}"]
        }
        if upstreams.isEmpty {
            lines += ["", "http://localhost {", "\trespond \"ColimaX proxy: no routes\" 404", "}"]
        }
        return lines.joined(separator: "\n") + "\n"
    }

    // MARK: Container lifecycle

    struct Status: Equatable, Sendable {
        let exists: Bool
        let running: Bool
        let id: String?
    }

    static func status(client: any DockerEngine, name: String = containerName) async throws -> Status {
        let containers = try await client.containers()
        guard let proxy = containers.first(where: { $0.labels?[label] != nil && $0.name == name }) else {
            return Status(exists: false, running: false, id: nil)
        }
        return Status(exists: true, running: proxy.isRunning, id: proxy.id)
    }

    /// `name` / `volume` / `extraLabels` are overridden only by integration tests (`colimax-test-*` resources).
    static func create(settings: ProxySettings, client: any DockerEngine, name: String = containerName,
                       volume: String = dataVolume, extraLabels: [String: String] = [:]) async throws -> String {
        guard settings.isValid else { throw ProxyError.invalid(String(localized: "Invalid proxy ports")) }
        if !(await client.imageExists(image)) {
            for try await progress in client.pull(image) {
                if let error = progress.error { throw DockerError.socket(error) }
            }
        }
        struct Restart: Encodable, Sendable { let Name: String }
        struct HostConfig: Encodable, Sendable {
            let NetworkMode: String
            let Binds: [String]
            let RestartPolicy: Restart
        }
        struct Body: Encodable, Sendable {
            let Image: String
            let Labels: [String: String]
            let HostConfig: HostConfig
        }
        let body = Body(
            Image: image,
            Labels: extraLabels.merging([label: "1"]) { _, new in new },
            HostConfig: HostConfig(NetworkMode: "host", Binds: ["\(volume):/data"], RestartPolicy: Restart(Name: "unless-stopped"))
        )
        let id = try await client.createContainer(name: name, body: body)
        // The image's default Caddyfile listens on :80 on all interfaces, so write the app's config before starting.
        try await writeCaddyfile(caddyfile([], settings: settings), proxyID: id, client: client)
        try await client.containerAction(id, "start")
        return id
    }

    private static func writeCaddyfile(_ content: String, proxyID: String, client: any DockerEngine) async throws {
        let file = FileManager.default.temporaryDirectory.appendingPathComponent("colimax-Caddyfile-\(UUID().uuidString.prefix(8))")
        try AtomicFile.write(Data(content.utf8), to: file, permissions: 0o600)
        defer { try? FileManager.default.removeItem(at: file) }
        try await client.uploadAsTar(container: proxyID, directory: caddyfilePath, file: file, entryName: "Caddyfile", mode: 0o644, timeout: 60)
    }

    /// Removes the proxy container. The CA volume is kept so an already trusted certificate stays valid.
    static func remove(client: any DockerEngine) async throws {
        let current = try await status(client: client)
        guard let id = current.id else { return }
        try await client.removeContainer(id, force: true, volumes: false)
    }

    /// Writes the Caddyfile and reloads Caddy. Returns the skipped routes (missing or stopped container, ...).
    @discardableResult
    static func apply(routes: [ProxyRoute], settings: ProxySettings, proxyID: String, client: any DockerEngine) async throws -> [String] {
        var upstreams: [Upstream] = []
        var skipped: [String] = []
        let containers = try await client.containers()
        for route in routes where route.isValid {
            guard let target = containers.first(where: { $0.name == route.container }) else {
                skipped.append("\(route.host): \(ProxyError.targetMissing(route.container).localizedDescription)")
                continue
            }
            guard target.isRunning else {
                skipped.append(String(localized: "\(route.host): container \(route.container) is not running"))
                continue
            }
            do {
                upstreams.append(try upstream(for: route, target: try await client.containerDetails(target.id)))
            } catch {
                skipped.append("\(route.host): \(error.localizedDescription)")
            }
        }
        try await writeCaddyfile(caddyfile(upstreams, settings: settings), proxyID: proxyID, client: client)
        try await reload(proxyID: proxyID, client: client)
        return skipped
    }

    /// `caddy reload` reads the admin address from the Caddyfile itself. Right after the container starts
    /// the admin API may not be ready yet: connection errors are retried for about 10 s, while
    /// configuration errors are reported immediately.
    static func reload(proxyID: String, client: any DockerEngine, attempts: Int = 20) async throws {
        var last = ""
        for attempt in 0..<max(1, attempts) {
            let result = try await client.exec(proxyID, argv: ["caddy", "reload", "--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"], timeout: 60)
            if result.exitCode == 0 { return }
            last = result.output.trimmed
            guard isAdminNotReady(last), attempt + 1 < attempts else { break }
            try await Task.sleep(for: .milliseconds(500))
        }
        throw ProxyError.reloadFailed(String(last.suffix(600)))
    }

    static func isAdminNotReady(_ output: String) -> Bool {
        let lowered = output.lowercased()
        return lowered.contains("connection refused") || lowered.contains("no such file or directory") && lowered.contains("admin")
    }

    // MARK: Root CA

    /// Fetches Caddy's root CA (PEM) from the container.
    static func rootCertificate(proxyID: String, client: any DockerEngine) async throws -> Data {
        let tar = try await client.archiveData(container: proxyID, path: rootCertPath)
        guard let entry = TarReader.firstFile(tar), String(decoding: entry.data.prefix(27), as: UTF8.self).hasPrefix("-----BEGIN CERTIFICATE-----") else {
            throw ProxyError.invalid(String(localized: "Caddy has not created its local CA yet. Open one HTTPS route first, then try again."))
        }
        return entry.data
    }

    static var certificateFile: URL {
        MetricsHistory.directory().deletingLastPathComponent().appendingPathComponent("caddy-root.crt")
    }

    /// Adds the root CA to the login keychain as trusted for SSL. macOS shows its own authentication
    /// dialog; the app never sees the password.
    static func trustRootCertificate(_ pem: Data) async throws {
        let file = certificateFile
        try FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        try AtomicFile.write(pem, to: file, permissions: 0o644)
        let keychain = URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent("Library/Keychains/login.keychain-db").path
        let result = try await Shell.run("security", ["add-trusted-cert", "-r", "trustRoot", "-p", "ssl", "-k", keychain, file.path], timeout: 300)
        guard result.ok else { throw ProxyError.invalid(String(localized: "security add-trusted-cert failed: \(result.stderr.trimmed)")) }
    }

    /// Removes the trust setting (the certificate stays in the keychain but is no longer trusted).
    static func untrustRootCertificate() async throws {
        let file = certificateFile
        guard FileManager.default.fileExists(atPath: file.path) else { return }
        let result = try await Shell.run("security", ["remove-trusted-cert", file.path], timeout: 300)
        guard result.ok else { throw ProxyError.invalid(String(localized: "security remove-trusted-cert failed: \(result.stderr.trimmed)")) }
    }
}

/// Reads the first regular file from a small tar (e.g. a certificate fetched via the archive API).
enum TarReader {
    static func firstFile(_ data: Data) -> (name: String, data: Data)? {
        let bytes = [UInt8](data)
        var offset = 0
        while offset + 512 <= bytes.count {
            let header = bytes[offset..<offset + 512]
            if header.allSatisfy({ $0 == 0 }) { return nil }
            let name = String(decoding: header.prefix(100).prefix { $0 != 0 }, as: UTF8.self)
            let sizeField = String(decoding: bytes[offset + 124..<offset + 136].prefix { $0 != 0 && $0 != 0x20 }, as: UTF8.self)
            guard let size = Int(sizeField, radix: 8) else { return nil }
            let type = bytes[offset + 156]
            let start = offset + 512
            if type == UInt8(ascii: "0") || type == 0 {
                guard start + size <= bytes.count else { return nil }
                return (name, Data(bytes[start..<start + size]))
            }
            offset = start + (size + 511) / 512 * 512
        }
        return nil
    }
}
